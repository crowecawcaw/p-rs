    /// True for the keywords that only the PVerifier backend accepts.
    pub fn is_verifier_only(self) -> bool {
        use TokenKind::*;
        matches!(
            self,
            Invariant
                | Axiom
                | Is
                | Inflight
                | Targets
                | Sent
                | Proof
                | Prove
                | Using
                | Lemma
                | Theorem
                | Except
                | Requires
                | Ensures
                | Forall
                | Exists
                | InitCondition
                | Pure
        )
    }
